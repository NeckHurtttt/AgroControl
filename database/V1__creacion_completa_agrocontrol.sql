-- 9. labor · RN-02 (pertenece a una campaña, y la parcela se obtiene por ella)
CREATE TABLE labor (
    labor_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    campana_id      BIGINT       NOT NULL,
    codigo          VARCHAR(30)  NOT NULL,
    tipo            VARCHAR(25)  NOT NULL,
    descripcion     TEXT         NULL,
    fecha_planificada DATE       NOT NULL,
    fecha_inicio_real TIMESTAMPTZ NULL,
    fecha_fin_real  TIMESTAMPTZ  NULL,
    estado          VARCHAR(20)  NOT NULL DEFAULT 'PLANIFICADA',
    motivo_cancelacion TEXT      NULL,
    created_by      BIGINT       NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_labor PRIMARY KEY (labor_id),
    CONSTRAINT fk_labor_campana FOREIGN KEY (campana_id) REFERENCES campana (campana_id),
    CONSTRAINT fk_labor_created_by FOREIGN KEY (created_by) REFERENCES usuario (usuario_id),
    CONSTRAINT uq_labor_campana_codigo UNIQUE (campana_id, codigo),
    CONSTRAINT ck_labor_tipo CHECK (tipo IN
        ('PREPARACION','SIEMBRA','FERTILIZACION','RIEGO','CONTROL_MALEZA',
         'CONTROL_PLAGA','PODA','MONITOREO','COSECHA','OTRA')),
    CONSTRAINT ck_labor_estado CHECK (estado IN
        ('PLANIFICADA','ASIGNADA','EN_EJECUCION','COMPLETADA','CANCELADA')),
    CONSTRAINT ck_labor_fechas_reales CHECK
        (fecha_fin_real IS NULL OR fecha_inicio_real IS NULL OR fecha_fin_real >= fecha_inicio_real),
    CONSTRAINT ck_labor_cancelacion CHECK
        (estado <> 'CANCELADA' OR motivo_cancelacion IS NOT NULL),
    CONSTRAINT ck_labor_completada CHECK
        (estado <> 'COMPLETADA' OR fecha_fin_real IS NOT NULL)
);

