-- ---------------------------------------------------------------------
-- RN-09 · No se elimina el historial de campañas terminadas
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_impedir_borrado_historico()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'RN-09: los registros de % no se pueden eliminar', TG_TABLE_NAME;
END;
$$;

CREATE TRIGGER trg_bitacora_no_delete
    BEFORE DELETE ON bitacora_campo
    FOR EACH ROW EXECUTE FUNCTION fn_impedir_borrado_historico();

CREATE TRIGGER trg_movimiento_insumo_no_delete
    BEFORE DELETE ON movimiento_insumo
    FOR EACH ROW EXECUTE FUNCTION fn_impedir_borrado_historico();

CREATE TRIGGER trg_historial_labor_no_delete
    BEFORE DELETE ON historial_estado_labor
    FOR EACH ROW EXECUTE FUNCTION fn_impedir_borrado_historico();

CREATE TRIGGER trg_auditoria_no_delete
    BEFORE DELETE ON auditoria
    FOR EACH ROW EXECUTE FUNCTION fn_impedir_borrado_historico();

-- RN-09 · Una campaña FINALIZADA no vuelve atrás ni se borra
CREATE OR REPLACE FUNCTION fn_proteger_campana_finalizada()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'RN-09: no se elimina una campaña (%), su historial debe conservarse', OLD.codigo;
    END IF;
    IF OLD.estado = 'FINALIZADA' AND NEW.estado <> 'FINALIZADA' THEN
        RAISE EXCEPTION 'RN-09: la campaña % ya está finalizada y no puede reabrirse', OLD.codigo;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_campana_protegida
    BEFORE UPDATE OR DELETE ON campana
    FOR EACH ROW EXECUTE FUNCTION fn_proteger_campana_finalizada();

-- ---------------------------------------------------------------------
-- RF-15 · Bitácora consolidada por parcela (vista, no tabla duplicada)
-- ---------------------------------------------------------------------
CREATE VIEW vw_bitacora_parcela AS
SELECT b.registrado_at,
       p.predio_id,
       pa.parcela_id,
       pa.codigo        AS codigo_parcela,
       c.codigo         AS campana,
       l.codigo         AS labor,
       b.tipo_registro,
       b.observacion,
       us.username      AS registrado_por
FROM bitacora_campo b
JOIN parcela pa  ON pa.parcela_id = b.parcela_id
JOIN predio p    ON p.predio_id = pa.predio_id
LEFT JOIN campana c ON c.campana_id = b.campana_id
LEFT JOIN labor l   ON l.labor_id = b.labor_id
JOIN usuario us  ON us.usuario_id = b.registrado_por;

