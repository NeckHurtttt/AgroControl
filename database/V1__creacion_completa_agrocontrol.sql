-- 6. parcela  (ENTIDAD DEPENDIENTE del par 1:N)
CREATE TABLE parcela (
    parcela_id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    predio_id             BIGINT        NOT NULL,
    codigo                VARCHAR(30)   NOT NULL,
    nombre                VARCHAR(120)  NOT NULL,
    superficie_hectareas  NUMERIC(10,4) NOT NULL,
    tipo_suelo            VARCHAR(30)   NULL,
    estado                VARCHAR(20)   NOT NULL DEFAULT 'DISPONIBLE',
    observacion           TEXT          NULL,
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT pk_parcela PRIMARY KEY (parcela_id),
    CONSTRAINT fk_parcela_predio FOREIGN KEY (predio_id) REFERENCES predio (predio_id),
